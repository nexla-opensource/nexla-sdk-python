#!/usr/bin/env python3
"""Generate the async client modules under nexla_sdk/aio from the sync sources.

This is an unasync-style transform. It reads the sync modules with ``ast``
and edits the source text at exact offsets. Comments and layout survive, and
ruff formats the result.

1. A method is async when its body awaits request I/O. The roots are calls to
   ``request()`` and ``request_with_headers()``. A method is async too when it
   calls an async method: ``self.m()``, or ``self.client.<attr>.m()`` where
   ``<attr>`` is a resource on NexlaClient. A fixed-point pass finds these.
2. Each call to an async method is awaited.
3. Imports point at the ``nexla_sdk.aio`` tree. Names listed in RENAMES are renamed.
   ``threading.RLock()`` becomes ``AsyncReentrantLock()``, and ``with self._lock``
   becomes ``async with``.

Outputs carry a generated-file header. Do not edit them. Run this script after a
sync module changes, then commit the result. CI runs it and fails on any diff.

Usage: python scripts/gen_async.py
"""

from __future__ import annotations

import ast
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterator, List, Optional, Set, Tuple

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / "nexla_sdk"
AIO = PKG / "aio"
MARKER = "# AUTO-GENERATED by scripts/gen_async.py"

IO_ROOTS = frozenset({"request", "request_with_headers"})

# Names renamed in code and string annotations.
RENAMES = {
    "NexlaClient": "AsyncNexlaClient",
    "RequestsHttpClient": "AsyncHttpxClient",
    "HttpClientInterface": "AsyncHttpClientInterface",
    "Paginator": "AsyncPaginator",
}

# (module, name) -> (module, name) for imports whose target changes.
IMPORT_MAP: Dict[Tuple[str, str], Tuple[str, str]] = {
    ("nexla_sdk.client", "NexlaClient"): ("nexla_sdk.aio.client", "AsyncNexlaClient"),
    ("nexla_sdk.http_client", "RequestsHttpClient"): (
        "nexla_sdk.aio.http_client",
        "AsyncHttpxClient",
    ),
    ("nexla_sdk.http_client", "HttpClientInterface"): (
        "nexla_sdk.aio.http_client",
        "AsyncHttpClientInterface",
    ),
    ("nexla_sdk.http_client", "HttpClientError"): (
        "nexla_sdk.transport_core",
        "HttpClientError",
    ),
    ("nexla_sdk.http_client", "HttpTimeoutError"): (
        "nexla_sdk.transport_core",
        "HttpTimeoutError",
    ),
    ("nexla_sdk.http_client", "HttpConnectionError"): (
        "nexla_sdk.transport_core",
        "HttpConnectionError",
    ),
    ("nexla_sdk.utils.pagination", "Paginator"): (
        "nexla_sdk.aio.pagination",
        "AsyncPaginator",
    ),
}

# Modules whose path moves under nexla_sdk.aio (prefix rule).
MOVED_PREFIXES = ("nexla_sdk.resources", "nexla_sdk.auth", "nexla_sdk.raw_operations")

LOCK_MODULE = "nexla_sdk.aio._locks"
LOCK_NAME = "AsyncReentrantLock"


def sync_sources() -> List[Path]:
    """Sync modules that the transform reads. Each one has an aio output."""
    return [PKG / "auth.py", PKG / "raw_operations.py"] + sorted(
        (PKG / "resources").glob("*.py")
    )


def output_path(src: Path) -> Path:
    return AIO / src.relative_to(PKG)


def package_of(src: Path) -> str:
    """Dotted package used to resolve relative imports in ``src``."""
    return ".".join(src.relative_to(ROOT).with_suffix("").parts[:-1])


def absolute_module(node: ast.ImportFrom, package: str) -> str:
    if node.level == 0:
        return node.module or ""
    parts = package.split(".")
    base = parts[: len(parts) - (node.level - 1)]
    if node.module:
        base.append(node.module)
    return ".".join(base)


def map_import(module: str, name: str) -> Tuple[str, str]:
    if (module, name) in IMPORT_MAP:
        return IMPORT_MAP[(module, name)]
    if module.startswith(MOVED_PREFIXES):
        return "nexla_sdk.aio" + module[len("nexla_sdk") :], name
    return module, name


@dataclass
class ClassInfo:
    module: str
    bases: List[str]
    methods: Dict[str, ast.FunctionDef]


class Analysis:
    """Class index, client attribute map and the set of async methods."""

    def __init__(self, classes: Dict[str, ClassInfo], attr_classes: Dict[str, str]):
        self.classes = classes
        self.attr_classes = attr_classes
        self.async_methods: Set[Tuple[str, str]] = set()

    def method_is_async(self, cls: str, name: str) -> bool:
        if (cls, name) in self.async_methods:
            return True
        if cls not in self.classes:
            return False
        info = self.classes[cls]
        if name in info.methods:
            return False
        return any(
            base in self.classes and self.method_is_async(base, name)
            for base in info.bases
        )

    def is_async_call(self, cls: Optional[str], call: ast.Call) -> bool:
        func = call.func
        if not isinstance(func, ast.Attribute):
            return False
        if func.attr in IO_ROOTS:
            return True
        value = func.value
        if cls is not None and isinstance(value, ast.Name) and value.id == "self":
            return self.method_is_async(cls, func.attr)
        if cls is not None and _is_super_call(value):
            return any(
                self.method_is_async(base, func.attr)
                for base in self.classes[cls].bases
                if base in self.classes
            )
        if (
            isinstance(value, ast.Attribute)
            and isinstance(value.value, ast.Attribute)
            and isinstance(value.value.value, ast.Name)
            and value.value.value.id == "self"
            and value.value.attr == "client"
        ):
            target = self.attr_classes.get(value.attr)
            return target is not None and self.method_is_async(target, func.attr)
        return False

    def method_has_io(self, cls: str, fn: ast.FunctionDef) -> bool:
        for call, nested in scoped_calls(fn):
            if self.is_async_call(cls, call):
                if nested:
                    raise SystemExit(
                        f"{cls}.{fn.name}: I/O inside a nested function or lambda "
                        "is not supported by gen_async.py"
                    )
                return True
        return False


def _is_super_call(expr: ast.expr) -> bool:
    """True for ``super()``, the receiver of ``super().method(...)``."""
    return (
        isinstance(expr, ast.Call)
        and isinstance(expr.func, ast.Name)
        and expr.func.id == "super"
    )


def scoped_calls(
    node: ast.AST, nested: bool = False
) -> Iterator[Tuple[ast.Call, bool]]:
    """Yield (call, inside_nested_scope) for every call under ``node``."""
    for child in ast.iter_child_nodes(node):
        if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)):
            yield from scoped_calls(child, True)
            continue
        if isinstance(child, ast.Call):
            yield child, nested
        yield from scoped_calls(child, nested)


def client_attribute_classes(tree: ast.Module) -> Dict[str, str]:
    """Map NexlaClient attributes to resource class names: ``self.flows = FlowsResource(self)``."""
    client = next(
        n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "NexlaClient"
    )
    init = next(
        n
        for n in client.body
        if isinstance(n, ast.FunctionDef) and n.name == "__init__"
    )
    out: Dict[str, str] = {}
    for stmt in init.body:
        if isinstance(stmt, ast.Assign):
            targets, value = stmt.targets, stmt.value
        elif isinstance(stmt, ast.AnnAssign) and stmt.value is not None:
            targets, value = [stmt.target], stmt.value
        else:
            continue
        if not isinstance(value, ast.Call) or not isinstance(value.func, ast.Name):
            continue
        for target in targets:
            if (
                isinstance(target, ast.Attribute)
                and isinstance(target.value, ast.Name)
                and target.value.id == "self"
            ):
                out[target.attr] = value.func.id
    return out


def base_name(expr: ast.expr) -> Optional[str]:
    if isinstance(expr, ast.Subscript):
        expr = expr.value
    return expr.id if isinstance(expr, ast.Name) else None


def build_analysis(trees: Dict[Path, ast.Module]) -> Analysis:
    classes: Dict[str, ClassInfo] = {}
    for src, tree in trees.items():
        for node in tree.body:
            if not isinstance(node, ast.ClassDef):
                continue
            if node.name in classes:
                raise SystemExit(f"duplicate class name {node.name}")
            methods = {n.name: n for n in node.body if isinstance(n, ast.FunctionDef)}
            bases = [b for b in (base_name(x) for x in node.bases) if b]
            classes[node.name] = ClassInfo(
                module=src.name, bases=bases, methods=methods
            )
    client_tree = ast.parse((PKG / "client.py").read_bytes())
    return Analysis(classes, client_attribute_classes(client_tree))


def solve_async(an: Analysis) -> None:
    """Mark every method that awaits I/O. Repeat until nothing changes."""
    methods = [
        (name, fn) for name, info in an.classes.items() for fn in info.methods.values()
    ]
    changed = True
    while changed:
        changed = False
        for cls, fn in methods:
            key = (cls, fn.name)
            if key in an.async_methods:
                continue
            if an.method_has_io(cls, fn):
                an.async_methods.add(key)
                changed = True


def line_offsets(source: bytes) -> List[int]:
    starts = [0]
    for index, byte in enumerate(source):
        if byte == 0x0A:
            starts.append(index + 1)
    return starts


def import_replacement(
    node: ast.ImportFrom, package: str, indent: int
) -> Optional[str]:
    module = absolute_module(node, package)
    if not (node.level or module.startswith("nexla_sdk")):
        return None
    groups: Dict[str, List[str]] = {}
    for alias in node.names:
        new_module, new_name = map_import(module, alias.name)
        piece = new_name if alias.asname is None else f"{new_name} as {alias.asname}"
        groups.setdefault(new_module, []).append(piece)
    lines = [f"from {mod} import {', '.join(names)}" for mod, names in groups.items()]
    return ("\n" + " " * indent).join(lines)


def rewrite(src: Path, tree: ast.Module, an: Analysis) -> bytes:
    source = src.read_bytes()
    starts = line_offsets(source)

    def at(line: int, col: int) -> int:
        # ast columns are UTF-8 byte offsets, which is what the source bytes index.
        return starts[line - 1] + col

    edits: List[Tuple[int, int, bytes]] = []
    package = package_of(src)
    lock_used = any(
        _is_threading_rlock(n) for n in ast.walk(tree) if isinstance(n, ast.Call)
    )
    parents: Dict[ast.AST, ast.AST] = {}
    for node in ast.walk(tree):
        for child in ast.iter_child_nodes(node):
            parents[child] = node

    # Methods and calls.
    cls_nodes = [n for n in tree.body if isinstance(n, ast.ClassDef)]
    for cls_node in cls_nodes:
        for fn in cls_node.body:
            if not isinstance(fn, ast.FunctionDef):
                continue
            if (cls_node.name, fn.name) in an.async_methods:
                edits.append(
                    (
                        at(fn.lineno, fn.col_offset),
                        at(fn.lineno, fn.col_offset),
                        b"async ",
                    )
                )
            for call, _ in scoped_calls(fn):
                if not an.is_async_call(cls_node.name, call):
                    continue
                start = at(call.lineno, call.col_offset)
                end = at(call.end_lineno, call.end_col_offset)
                parent = parents.get(call)
                if isinstance(parent, (ast.Attribute, ast.Subscript)) or (
                    isinstance(parent, ast.Call) and parent.func is call
                ):
                    edits.append((start, start, b"(await "))
                    edits.append((end, end, b")"))
                else:
                    edits.append((start, start, b"await "))
            for node in ast.walk(fn):
                if isinstance(node, ast.With) and _is_self_lock(
                    node.items[0].context_expr
                ):
                    if (cls_node.name, fn.name) not in an.async_methods:
                        raise SystemExit(
                            f"{src.name}: with self._lock outside an async method"
                        )
                    edits.append(
                        (
                            at(node.lineno, node.col_offset),
                            at(node.lineno, node.col_offset),
                            b"async ",
                        )
                    )

    # Module-level functions must not do I/O. A call there has no class to await in.
    for node in tree.body:
        if isinstance(node, ast.FunctionDef):
            for call, _ in scoped_calls(node):
                if an.is_async_call(None, call):
                    raise SystemExit(
                        f"{src.name}: module-level function {node.name} does I/O"
                    )

    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and _is_threading_rlock(node):
            edits.append(
                (
                    at(node.lineno, node.col_offset),
                    at(node.end_lineno, node.end_col_offset),
                    f"{LOCK_NAME}()".encode(),
                )
            )
        elif isinstance(node, ast.Name) and node.id in RENAMES:
            edits.append(
                (
                    at(node.lineno, node.col_offset),
                    at(node.end_lineno, node.end_col_offset),
                    RENAMES[node.id].encode(),
                )
            )
        elif (
            isinstance(node, ast.Constant)
            and isinstance(node.value, str)
            and node.value in RENAMES
        ):
            edits.append(
                (
                    at(node.lineno, node.col_offset),
                    at(node.end_lineno, node.end_col_offset),
                    f'"{RENAMES[node.value]}"'.encode(),
                )
            )

    # Imports.
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom):
            text = import_replacement(node, package, node.col_offset)
            if text is not None:
                edits.append(
                    (
                        at(node.lineno, node.col_offset),
                        at(node.end_lineno, node.end_col_offset),
                        text.encode(),
                    )
                )
        elif (
            isinstance(node, ast.Import)
            and lock_used
            and any(a.name == "threading" for a in node.names)
        ):
            edits.append(
                (
                    at(node.lineno, node.col_offset),
                    at(node.end_lineno, node.end_col_offset),
                    f"from {LOCK_MODULE} import {LOCK_NAME}".encode(),
                )
            )

    return apply_edits(source, edits, src)


def _is_self_lock(expr: ast.expr) -> bool:
    return (
        isinstance(expr, ast.Attribute)
        and isinstance(expr.value, ast.Name)
        and expr.value.id == "self"
        and expr.attr == "_lock"
    )


def _is_threading_rlock(node: ast.Call) -> bool:
    func = node.func
    return (
        isinstance(func, ast.Attribute)
        and isinstance(func.value, ast.Name)
        and func.value.id == "threading"
        and func.attr == "RLock"
    )


def apply_edits(source: bytes, edits: List[Tuple[int, int, bytes]], src: Path) -> bytes:
    out = bytearray()
    cursor = 0
    for start, end, text in sorted(edits, key=lambda e: (e[0], e[1])):
        if start < cursor:
            raise SystemExit(f"{src}: overlapping edits at byte {start}")
        out += source[cursor:start] + text
        cursor = end
    out += source[cursor:]
    return bytes(out)


def format_outputs(paths: List[Path]) -> None:
    args = [str(p) for p in paths]
    subprocess.run(
        [sys.executable, "-m", "ruff", "check", "--fix", "--select", "I,F401", *args],
        cwd=ROOT,
        check=True,
        stdout=subprocess.DEVNULL,
    )
    subprocess.run(
        [sys.executable, "-m", "ruff", "format", *args],
        cwd=ROOT,
        check=True,
        stdout=subprocess.DEVNULL,
    )


def main() -> int:
    trees: Dict[Path, ast.Module] = {}
    for src in sync_sources():
        trees[src] = ast.parse(src.read_bytes(), filename=str(src))
    an = build_analysis(trees)
    solve_async(an)

    produced: List[Path] = []
    for src in sync_sources():
        out = output_path(src)
        out.parent.mkdir(parents=True, exist_ok=True)
        body = rewrite(src, trees[src], an)
        header = f"{MARKER} from nexla_sdk/{src.relative_to(PKG)}. Do not edit.\n# Regenerate with: python scripts/gen_async.py\n"
        out.write_bytes(header.encode() + body)
        ast.parse(out.read_bytes(), filename=str(out), feature_version=(3, 8))
        produced.append(out)

    # Resource __init__ re-exports are part of the sync sources and produced above.
    # Remove generated resource modules whose sync source no longer exists.
    keep = {p.name for p in produced if p.parent == AIO / "resources"}
    for stale in (AIO / "resources").glob("*.py"):
        if stale.name not in keep and MARKER in stale.read_text(encoding="utf-8"):
            stale.unlink()

    format_outputs(produced)
    print(f"generated {len(produced)} modules; {len(an.async_methods)} async methods")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
